/**
 * Regenerates packages/contract/src/towns.ts from the official CWA township list
 * (M-A0085-001 carries every township's geocode and centroid). Run by hand when
 * administrative divisions change: `npm run gen:towns`.
 */
import { writeFile } from "node:fs/promises";
import { COUNTIES, normalizeCountyName } from "../packages/contract/src/counties";

const SOURCE = "https://cwaopendata.s3.ap-northeast-1.amazonaws.com/Model/M-A0085-001.json";
const OUT = new URL("../packages/contract/src/towns.ts", import.meta.url);

type Raw = { TownName?: string; Geocode?: string; Latitude?: string; Longitude?: string };

const payload = (await (await fetch(SOURCE)).json()) as {
  cwaopendata: { Resources: { Resource: { Data: { Locations: Array<{ CountyName: string; Location: Raw[] }> } } } };
};
const rows: string[] = [];
const order = new Map(COUNTIES.map((c, i) => [c.name, i]));
const towns = payload.cwaopendata.Resources.Resource.Data.Locations.flatMap((c) => {
  const county = normalizeCountyName(c.CountyName);
  if (!county) throw new Error(`unknown county ${c.CountyName}`);
  return c.Location.map((t) => {
    const lat = Number(t.Latitude);
    const lon = Number(t.Longitude);
    if (!t.TownName || !t.Geocode || !Number.isFinite(lat) || !Number.isFinite(lon)) throw new Error(`bad town in ${county}`);
    return { county, town: t.TownName, geocode: t.Geocode, lat: Number(lat.toFixed(4)), lon: Number(lon.toFixed(4)) };
  });
}).sort((a, b) => order.get(a.county)! - order.get(b.county)! || a.geocode.localeCompare(b.geocode));

if (towns.length !== 368) throw new Error(`expected 368 townships, got ${towns.length}`);
for (const t of towns) rows.push(`  ["${t.county}", "${t.town}", "${t.geocode}", ${t.lat}, ${t.lon}],`);

await writeFile(
  OUT,
  `// Generated by scripts/gen-towns.ts from CWA M-A0085-001 — do not edit by hand.
// [county, town, geocode, latitude, longitude] for all ${towns.length} townships.
export const TOWN_ROWS: ReadonlyArray<readonly [string, string, string, number, number]> = [
${rows.join("\n")}
];
`,
);
console.log(`wrote ${towns.length} townships`);
